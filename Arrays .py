# Creating an array (list)
numbers = [10, 20, 30, 40, 50]

# Accessing elements
print(numbers[0])   # First element
print(numbers[2])   # Third element

# Adding elements
numbers.append(60)

# Removing elements
numbers.remove(20)

# Loop through array
for num in numbers:
    print(num)

# Length of array
print("Length:", len(numbers))